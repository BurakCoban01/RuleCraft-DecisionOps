import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from '@playwright/test';
import { LocalClient, localOrigin } from './client.mjs';
import { projectKey, serviceKey } from './scenario.mjs';

const origin = localOrigin(process.env.RULECRAFT_SHOWCASE_ORIGIN ?? 'http://127.0.0.1:50111');
const workspace = process.env.RULECRAFT_SHOWCASE_WORKSPACE ?? 'northstar-rules';
const email = process.env.RULECRAFT_SHOWCASE_EMAIL;
const password = process.env.RULECRAFT_SHOWCASE_PASSWORD;
assert(workspace === 'northstar-rules' && email?.endsWith('.test') && password, 'Use the dedicated synthetic local workspace.');
const output = path.resolve(process.env.RULECRAFT_SHOWCASE_CAPTURE_DIR ?? 'test-results/showcase');
const width = Number(process.env.RULECRAFT_SHOWCASE_WIDTH ?? 1600);
const height = width < 761 ? 740 : width === 1440 ? 900 : 1000;
await mkdir(output, { recursive: true });
const client = await LocalClient.signIn(origin, workspace, email, password);
const project = (await client.call('/api/v1/projects')).find(item => item.projectKey === projectKey);
assert(project, 'Populate the lending workspace first.');
const root = `/api/v1/projects/${project.id}`;
const service = (await client.call(`${root}/decision-services`)).find(item => item.serviceKey === serviceKey);
const graph = await client.call(`${root}/decision-services/${service.id}/graph`);
await client.close();
const graphPath = `/projects/${project.id}/services/${service.id}/graph`;
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ baseURL: origin, viewport: { width, height }, timezoneId: 'Europe/Istanbul', locale: 'en-GB', reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const screenshots = [];
const selected = process.env.RULECRAFT_SHOWCASE_ONLY?.split(',');
async function visit(route, selector) {
  await page.goto(route);
  await page.locator(selector).first().waitFor({ state: 'visible' });
  await page.waitForLoadState('networkidle');
}
async function capture(name, selector) {
  if (selected && !selected.includes(name)) return;
  if (selector) await page.locator(selector).evaluate(element => element.scrollIntoView({ block: 'start' }));
  await page.waitForLoadState('networkidle');
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.locator('.skeleton-lines:visible').count(), 0, `${name}: loading state`);
  assert.equal(await page.locator('[role="alert"]:visible').count(), 0, `${name}: unresolved error`);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false, `${name}: page overflow`);
  const filename = `${name}.png`;
  const content = await page.locator('.app-shell > main').boundingBox();
  const left = width >= 761 && !['decision-graph-lending', 'decision-table-lending'].includes(name) ? Math.max(0, Math.ceil(content.x)) : 0;
  await page.screenshot({ path: path.join(output, filename), animations: 'disabled', clip: { x: left, y: 0, width: width - left, height } });
  screenshots.push({ filename, width: width - left, height, route: new URL(page.url()).pathname });
}
try {
  await page.goto('/');
  await page.getByLabel('Workspace').fill(workspace);
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Continue to workspace' }).click();
  await page.getByRole('heading', { name: 'Projects', exact: true }).waitFor();
  if (process.env.RULECRAFT_SHOWCASE_THEME === 'dark') await page.getByRole('button', { name: 'Use dark theme', exact: true }).click();
  await capture('project-catalog');
  await visit(graphPath, '.graph-node');
  if (await page.getByRole('button', { name: 'Hide inspector', exact: true }).count()) await page.getByRole('button', { name: 'Hide inspector', exact: true }).click();
  if (width >= 761 && await page.getByRole('button', { name: 'Fit to content', exact: true }).count()) await page.getByRole('button', { name: 'Fit to content', exact: true }).click();
  await capture('decision-graph-lending');
  const policy = graph.nodes.find(item => item.nodeKey === 'policy');
  await visit(`${graphPath}/nodes/${policy.id}/table`, '.decision-table');
  if (await page.getByRole('button', { name: 'Review policy', exact: true }).count()) await page.getByRole('button', { name: 'Review policy', exact: true }).click();
  await capture('decision-table-lending');
  const affordability = graph.nodes.find(item => item.nodeKey === 'affordability');
  await visit(`${graphPath}/nodes/${affordability.id}/expression`, '.expression-diagnostics');
  await capture('expression-affordability');
  await visit(`${graphPath}/regression`, '.matrix-history-list button');
  await page.locator('.matrix-history-list button').first().click();
  await page.getByRole('heading', { name: 'Regression result', exact: true }).waitFor();
  await page.getByRole('button', { name: /Inspect evidence/ }).first().click();
  await capture('regression-suite');
  await visit(`${graphPath}/versions`, '.version-history');
  await page.getByRole('button', { name: 'Compare versions', exact: true }).click();
  await page.locator('.semantic-change').first().waitFor();
  await capture('version-diff', '.version-diff');
  await page.getByRole('button', { name: 'Approval & promotion', exact: true }).click();
  await page.locator('.promotion-banner').waitFor();
  await capture('version-governance');
  await visit(`${graphPath}/runtime`, '.trace-steps li');
  await capture('execution-trace', '.trace-explorer');
  await visit(`${graphPath}/analytics`, '.analytics-kpis');
  await capture('runtime-analytics');
  await visit(`${graphPath}/impact`, '.impact-scorecard');
  await capture('dependency-impact');
  await visit('/admin/operations', '.recovery-history article');
  await capture('operations-posture');
  await visit('/admin/users', '.workspace-page');
  await capture('team-access');
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'capture-report.json'), JSON.stringify({ synthetic: true, screenshots, errors }, null, 2));
  console.log(`Captured ${screenshots.length} real ${width}x${height} viewport candidates for visual review.`);
} finally { await context.close(); await browser.close(); }
