import { expect, test, type Page } from '@playwright/test';

async function signIn(page: Page) {
  await page.goto('/');
  await page.getByLabel('Workspace').fill('acme-rules');
  await page.getByLabel('Email').fill('admin@example.test');
  await page.getByLabel('Password').fill('CorrectHorseBattery12!');
  await page.getByRole('button', { name: 'Continue to workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Projects' })).toBeVisible({ timeout: 30_000 });
}

test('maps, captures, and reloads governed dependency impact', async ({ page }, testInfo) => {
  test.setTimeout(300_000);
  const runtimeErrors: string[] = [];
  const failedRequests: string[] = [];
  page.on('console', message => { if (message.type() === 'error') runtimeErrors.push(message.text()); });
  page.on('requestfailed', request => {
    const failure = request.failure()?.errorText ?? 'unknown';
    if (failure !== 'net::ERR_ABORTED') failedRequests.push(`${request.url()} · ${failure}`);
  });

  await signIn(page);
  page.setDefaultTimeout(15_000);
  const suffix = crypto.randomUUID().replaceAll('-', '').slice(0, 8).toUpperCase();
  const projectKey = `I${suffix}`;
  const serviceKey = `IMPACT_${suffix}`;
  await page.getByRole('button', { name: 'New project' }).click();
  await page.getByLabel('Project key').fill(projectKey);
  await page.getByLabel('Project name').fill(`Impact governance ${suffix}`);
  await page.getByRole('button', { name: 'Create project' }).click();
  await page.getByRole('button', { name: new RegExp(projectKey) }).click();
  await page.getByRole('button', { name: 'New decision service' }).click();
  await page.getByLabel('Service key').fill(serviceKey);
  await page.getByLabel('Name', { exact: true }).fill('Governed eligibility');
  const inputs = page.getByRole('group', { name: 'Inputs' });
  await inputs.getByLabel('Field key').fill('score');
  await inputs.getByLabel('Label').fill('Credit score');
  await inputs.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Create decision service' }).click();
  await page.getByRole('article').filter({ hasText: serviceKey }).getByRole('button', { name: 'Open graph' }).click();

  await page.getByRole('button', { name: 'Initialize decision graph' }).click();
  await page.getByRole('button', { name: 'Add decision' }).click();
  await page.getByLabel('Node key').fill('threshold');
  await page.getByLabel('Decision name').fill('Approval threshold');
  const ports = page.getByRole('group', { name: 'Required inputs' });
  await ports.getByLabel('Port key').fill('score');
  await ports.getByLabel('Label').fill('Score');
  await ports.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Add decision to canvas' }).click();
  await page.getByLabel('Source output').selectOption({ index: 1 });
  await page.getByLabel('Target input').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByLabel('Source output').selectOption({ index: 2 });
  await page.getByLabel('Target input').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByRole('button', { name: 'Save graph' }).click();
  await expect(page.getByText('Graph saved and validated.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('article').filter({ hasText: 'Approval threshold' }).getByRole('button', { name: 'Expression' }).click();
  await page.getByRole('button', { name: 'Initialize expression' }).click();
  await page.getByLabel('Expression source').fill('score >= 700');
  await page.getByRole('button', { name: 'Save expression' }).click();
  await expect(page.getByText('Expression saved and validated.')).toBeVisible({ timeout: 15_000 });

  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Test cases' }).click();
  await page.getByRole('button', { name: 'Create first scenario' }).click();
  await page.getByLabel('Test key').fill('approvedScore');
  await page.getByLabel('Scenario name').fill('Approved score remains stable');
  await page.getByLabel(/Credit score/).fill('750');
  await page.getByLabel(/Result/).selectOption('true');
  await page.getByRole('button', { name: 'Create scenario' }).click();
  await expect(page.getByText('Scenario created.')).toBeVisible();
  await page.getByRole('button', { name: 'Open regression matrix' }).click();
  await page.getByRole('button', { name: 'Select valid' }).click();
  await page.getByRole('button', { name: 'Run 1 selected' }).click();
  await expect(page.getByText('Matrix completed: 1 passed, 0 failed, 0 errors.')).toBeVisible({ timeout: 20_000 });

  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Versions' }).click();
  await page.getByRole('button', { name: 'Capture baseline' }).click();
  await page.getByLabel('Version label').fill('Governed impact candidate');
  await page.getByLabel('Review note').fill('Assurance evidence is aligned');
  await page.getByRole('button', { name: 'Capture working decision' }).click();
  await expect(page.getByText('Version 1 captured as valid.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Open change request' }).click();
  await page.getByLabel('Request title').fill('Publish governed eligibility');
  await page.getByLabel('Change summary').fill('Promote tested dependency baseline');
  await page.getByRole('button', { name: 'Create draft' }).click();
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await expect(page.getByText('CR-1 submitted for review.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Approve', exact: true }).click();
  await page.getByLabel('Decision note').fill('Dependency evidence reviewed');
  await page.getByRole('button', { name: 'Confirm action' }).click();
  await page.getByRole('button', { name: 'Promote baseline' }).click();
  await page.getByLabel('Decision note').fill('Promoted for governed runtime');
  await page.getByRole('button', { name: 'Confirm action' }).click();
  await expect(page.getByText('V1 is the governed baseline.')).toBeVisible({ timeout: 15_000 });

  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Runtime' }).click();
  await page.getByRole('button', { name: 'Deploy promoted version' }).click();
  await expect(page.getByText('Deployment #1 is active in the local sandbox.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Impact' }).click();
  await expect(page.getByRole('heading', { name: 'Impact analysis' })).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText('REVIEWABLE')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'No governance findings' })).toBeVisible();
  await expect(page.getByText('Approved score remains stable')).toBeVisible();
  await page.getByRole('button', { name: 'ASSURANCE' }).click();
  await expect(page.getByText('Approved score remains stable')).toBeVisible();
  await page.getByLabel('Search dependencies').fill('does-not-exist');
  await expect(page.getByRole('heading', { name: 'No dependencies match' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByRole('button', { name: 'Capture assessment' }).click();
  await expect(page.getByText('Immutable impact assessment captured.')).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText('Immutable assessment', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /LOW.*dependencies/ })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('workspace.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Impact analysis' })).toBeVisible({ timeout: 15_000 });
  await expect(page.getByRole('button', { name: /LOW.*dependencies/ })).toBeVisible();
  await page.getByRole('button', { name: /LOW.*dependencies/ }).click();
  await expect(page.getByText('Immutable assessment', { exact: true })).toBeVisible();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow).toBeLessThanOrEqual(0);
  expect(runtimeErrors).toEqual([]);
  expect(failedRequests).toEqual([]);
});
