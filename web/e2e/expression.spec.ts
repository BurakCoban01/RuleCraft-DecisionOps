import { expect, test, type Page } from '@playwright/test';

async function signIn(page: Page) {
  await page.goto('/');
  await page.getByLabel('Workspace').fill('acme-rules');
  await page.getByLabel('Email').fill('admin@example.test');
  await page.getByLabel('Password').fill('CorrectHorseBattery12!');
  await page.getByRole('button', { name: 'Continue to workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Projects' })).toBeVisible({ timeout: 30_000 });
}

test('diagnoses, corrects, and reloads a typed safe expression', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const runtimeErrors: string[] = []; const failedRequests: string[] = [];
  page.on('console', (message) => { if (message.type() === 'error') runtimeErrors.push(message.text()); });
  page.on('requestfailed', (request) => { const failure = request.failure()?.errorText ?? 'unknown'; if (failure !== 'net::ERR_ABORTED') failedRequests.push(`${request.url()} · ${failure}`); });
  await signIn(page);
  const suffix = Date.now().toString().slice(-7); const projectKey = `X${suffix}`;
  await page.getByRole('button', { name: 'New project' }).click();
  await page.getByLabel('Project key').fill(projectKey);
  await page.getByLabel('Project name').fill(`Expression decisions ${suffix}`);
  await page.getByRole('button', { name: 'Create project' }).click();
  await page.getByRole('button', { name: new RegExp(projectKey) }).click();
  await page.getByRole('button', { name: 'New decision service' }).click();
  await page.getByLabel('Service key').fill(`ELIG_${suffix}`);
  await page.getByLabel('Name', { exact: true }).fill('Eligibility expression');
  const inputs = page.getByRole('group', { name: 'Inputs' });
  await inputs.getByLabel('Field key').fill('score');
  await inputs.getByLabel('Label').fill('Applicant score');
  await inputs.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Create decision service' }).click();
  await page.getByRole('article').filter({ hasText: `ELIG_${suffix}` }).getByRole('button', { name: 'Open graph' }).click();
  await page.getByRole('button', { name: 'Initialize decision graph' }).click();
  await page.getByRole('button', { name: 'Add decision' }).click();
  await page.getByLabel('Node key').fill('eligibilityExpression');
  await page.getByLabel('Decision name').fill('Eligibility expression');
  const decisionInputs = page.getByRole('group', { name: 'Required inputs' });
  await decisionInputs.getByLabel('Port key').fill('score');
  await decisionInputs.getByLabel('Label').fill('Score');
  await decisionInputs.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Add decision to canvas' }).click();
  await page.getByLabel('Source output').selectOption({ label: 'Applicant score · Applicant score · NUMBER' });
  await page.getByLabel('Target input').selectOption({ label: 'Eligibility expression · Score · NUMBER' });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByLabel('Source output').selectOption({ label: 'Eligibility expression · Result · BOOLEAN' });
  await page.getByLabel('Target input').selectOption({ label: 'Result · Result · BOOLEAN' });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByRole('button', { name: 'Save graph' }).click();
  await expect(page.getByText('Graph saved and validated.')).toBeVisible();
  await page.getByRole('article').filter({ hasText: 'Eligibility expression' }).getByRole('button', { name: 'Expression' }).click();
  await page.getByRole('button', { name: 'Initialize expression' }).click();
  const source = page.getByLabel('Expression source');
  await source.fill('system(score)');
  await page.getByRole('button', { name: 'Save expression' }).click();
  await expect(page.getByText('Expression saved with validation issues.')).toBeVisible();
  await expect(page.getByText('FUNCTION', { exact: true })).toBeVisible();
  await source.fill('if score >= 700 then true else false');
  await page.getByRole('button', { name: 'Save expression' }).click();
  await expect(page.getByText('Expression saved and validated.')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Expression is type-safe' })).toBeVisible();
  await expect(page.getByText('Inferred result: BOOLEAN')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Eligibility expression' })).toBeVisible({ timeout: 15_000 });
  await expect(page.getByLabel('Expression source')).toHaveValue('if score >= 700 then true else false');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow).toBeLessThanOrEqual(0);
  await page.screenshot({ path: testInfo.outputPath('workspace.png'), fullPage: true });
  expect(runtimeErrors).toEqual([]); expect(failedRequests).toEqual([]);
});
