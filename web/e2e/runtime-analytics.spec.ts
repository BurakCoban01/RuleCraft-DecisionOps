import { expect, test, type Page } from '@playwright/test';

async function signIn(page: Page) {
  await page.goto('/');
  await page.getByLabel('Workspace').fill('acme-rules');
  await page.getByLabel('Email').fill('admin@example.test');
  await page.getByLabel('Password').fill('CorrectHorseBattery12!');
  await page.getByRole('button', { name: 'Continue to workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Projects' })).toBeVisible({ timeout: 30_000 });
}

test('reports persisted runtime evidence and benchmarks the active artifact', async ({ page, request }, testInfo) => {
  test.setTimeout(300_000);
  const runtimeErrors: string[] = [];
  const failedRequests: string[] = [];
  page.on('console', message => { if (message.type() === 'error') runtimeErrors.push(message.text()); });
  page.on('requestfailed', failed => { const reason = failed.failure()?.errorText ?? 'unknown'; if (reason !== 'net::ERR_ABORTED') failedRequests.push(`${failed.url()} · ${reason}`); });
  await signIn(page);
  const suffix = crypto.randomUUID().replaceAll('-', '').slice(0, 8).toUpperCase();
  const projectKey = `A${suffix}`;
  const serviceKey = `ANALYTICS_${suffix}`;

  await page.getByRole('button', { name: 'New project' }).click();
  await page.getByLabel('Project key').fill(projectKey);
  await page.getByLabel('Project name').fill(`Runtime analytics ${suffix}`);
  await page.getByRole('button', { name: 'Create project' }).click();
  await page.getByRole('button', { name: new RegExp(projectKey) }).click();
  await page.getByRole('button', { name: 'New decision service' }).click();
  await page.getByLabel('Service key').fill(serviceKey);
  await page.getByLabel('Name', { exact: true }).fill('Analytics eligibility');
  const inputs = page.getByRole('group', { name: 'Inputs' });
  await inputs.getByLabel('Field key').fill('score');
  await inputs.getByLabel('Label').fill('Credit score');
  await inputs.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Create decision service' }).click();
  await page.getByRole('article').filter({ hasText: serviceKey }).getByRole('button', { name: 'Open graph' }).click();

  await page.getByRole('button', { name: 'Initialize decision graph' }).click();
  await page.getByRole('button', { name: 'Add decision' }).click();
  await page.getByLabel('Node key').fill('threshold');
  await page.getByLabel('Decision name').fill('Approval threshold');
  const ports = page.getByRole('group', { name: 'Required inputs' });
  await ports.getByLabel('Port key').fill('score');
  await ports.getByLabel('Label').fill('Score');
  await ports.getByLabel('Type').selectOption('builtin:NUMBER');
  await page.getByRole('button', { name: 'Add decision to canvas' }).click();
  await page.getByLabel('Source output').selectOption({ label: 'Credit score · Credit score · NUMBER' });
  await page.getByLabel('Target input').selectOption({ label: 'Approval threshold · Score · NUMBER' });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByLabel('Source output').selectOption({ label: 'Approval threshold · Result · BOOLEAN' });
  await page.getByLabel('Target input').selectOption({ label: 'Result · Result · BOOLEAN' });
  await page.getByRole('button', { name: 'Add connection' }).click();
  await page.getByRole('button', { name: 'Save graph' }).click();
  await expect(page.getByText('Graph saved and validated.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('article').filter({ hasText: 'Approval threshold' }).getByRole('button', { name: 'Expression' }).click();
  await page.getByRole('button', { name: 'Initialize expression' }).click();
  await page.getByLabel('Expression source').fill('score >= 700');
  await page.getByRole('button', { name: 'Save expression' }).click();
  await expect(page.getByText('Expression saved and validated.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Versions' }).click();
  await page.getByRole('button', { name: 'Capture baseline' }).click();
  await page.getByLabel('Version label').fill('Analytics candidate');
  await page.getByLabel('Review note').fill('Runtime measurement contract reviewed');
  await page.getByRole('button', { name: 'Capture working decision' }).click();
  await expect(page.getByText('Version 1 captured as valid.')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Open change request' }).click();
  await page.getByLabel('Request title').fill('Publish measurable decision');
  await page.getByLabel('Change summary').fill('Approve immutable runtime measurement semantics');
  await page.getByRole('button', { name: 'Create draft' }).click();
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await page.getByRole('button', { name: 'Approve', exact: true }).click();
  await page.getByLabel('Decision note').fill('Analytics semantics reviewed');
  await page.getByRole('button', { name: 'Confirm action' }).click();
  await page.getByRole('button', { name: 'Promote baseline' }).click();
  await page.getByLabel('Decision note').fill('Promoted for runtime measurement');
  await page.getByRole('button', { name: 'Confirm action' }).click();
  await expect(page.getByText('V1 is the governed baseline.')).toBeVisible({ timeout: 15_000 });

  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Runtime' }).click();
  await page.getByRole('button', { name: 'Deploy promoted version' }).click();
  await expect(page.getByText('Deployment #1 is active in the local sandbox.')).toBeVisible({ timeout: 15_000 });
  await page.getByLabel(/Credit score/).fill('710');
  await page.getByRole('button', { name: 'Evaluate active artifact' }).click();
  await expect(page.locator('.runtime-probe-result pre')).toHaveText('true');
  await page.getByRole('button', { name: 'Run batch' }).click();
  await expect(page.getByText('Batch succeeded: 2 succeeded, 0 failed.')).toBeVisible({ timeout: 15_000 });
  await page.getByPlaceholder('Production decision client').fill('Analytics acceptance client');
  await page.getByRole('button', { name: 'Create API key' }).click();
  const secret = (await page.locator('.api-secret code').textContent())!;
  await page.getByRole('button', { name: 'I saved it' }).click();
  const endpoint = `http://127.0.0.1:50111/api/runtime/v1/decisions/${serviceKey}/evaluate`;
  const succeeded = await request.post(endpoint, { headers: { Authorization: `Bearer ${secret}` }, data: { requestId: crypto.randomUUID(), inputs: { score: 720 } } });
  expect(succeeded.status()).toBe(200);
  const failed = await request.post(endpoint, { headers: { Authorization: `Bearer ${secret}` }, data: { requestId: crypto.randomUUID(), inputs: { score: 'not-a-number' } } });
  expect(failed.status()).toBe(400);

  await page.getByRole('button', { name: 'Back to decision graph' }).click();
  await page.getByRole('button', { name: 'Analytics' }).click();
  await expect(page.getByRole('heading', { name: 'Runtime analytics', exact: true, level: 1 })).toBeVisible({ timeout: 15_000 });
  await expect(page.locator('.analytics-kpis').getByText('5', { exact: true }).first()).toBeVisible();
  await expect(page.locator('.channel-bars strong').filter({ hasText: 'SANDBOX' })).toBeVisible();
  await expect(page.locator('.channel-bars strong').filter({ hasText: 'WORKBENCH BATCH' })).toBeVisible();
  await expect(page.locator('.channel-bars strong').filter({ hasText: 'API SINGLE' })).toBeVisible();
  await expect(page.locator('.error-ranking')).toBeVisible();
  await page.getByLabel(/Credit score/).fill('710');
  await page.getByLabel('Measured iterations').selectOption('25');
  await page.getByLabel('Warmup iterations').selectOption('5');
  await page.getByRole('button', { name: 'Run benchmark' }).click();
  await expect(page.getByText('Benchmark completed across 25 measured iterations.')).toBeVisible({ timeout: 30_000 });
  await expect(page.locator('.benchmark-metrics')).toContainText('P95');
  await expect(page.locator('.benchmark-history')).toContainText('25 iterations');
  await expect(page.locator('.api-secret')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('workspace.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Runtime analytics', exact: true, level: 1 })).toBeVisible({ timeout: 15_000 });
  await expect(page.locator('.benchmark-history')).toContainText('25 iterations');
  await page.getByLabel('Runtime channel').selectOption('API_SINGLE');
  await expect(page.locator('.analytics-controls')).toHaveAttribute('aria-busy', 'false');
  await expect(page.locator('.analytics-kpis').getByText('2', { exact: true }).first()).toBeVisible();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow).toBeLessThanOrEqual(0);
  expect(runtimeErrors).toEqual([]);
  expect(failedRequests).toEqual([]);
});
